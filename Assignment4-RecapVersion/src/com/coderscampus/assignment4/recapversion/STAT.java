package com.coderscampus.assignment4.recapversion;

public abstract class STAT extends StudentTemplate {

	private int ID;
	private int grade;
	
	public int getID() {
		return ID;
	}
	public void setID(int iD) {
		ID = iD;
	}
	public int getGrade() {
		return grade;
	}
	public void setGrade(int grade) {
		this.grade = grade;
	}

	

}
